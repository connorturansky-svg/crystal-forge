import assert from 'node:assert/strict';
import {appendResourceVersion,pinResource,resolvePinnedResource,affectedPrintJobs} from '../src/resources/project-resources.mjs';
import {backupStatus} from '../src/resources/backup-status.mjs';
import {createProject,createModel,addModel,queueModel} from '../studio-documents.js';
const value={id:'custom-test',name:'Measured seed',kind:'seed',bodyDiameter:5,bodyHeight:9,flangeDiameter:5,flangeHeight:0,capHeight:1,wireWidth:2,wireDepth:1.5,measuredFit:{bodyDiameter:5,printedBoreDiameter:5.4}};
const input={id:value.id,kind:'pixel',name:'Seed A',value,calibratedAt:'2026-11-25',tags:['workshop','workshop']};
const first=appendResourceVersion(null,input),pin=pinResource(first,1);
const second=appendResourceVersion(first,{...input,expectedRevision:1,name:'Seed B',value:{...value,bodyHeight:10}});
assert.equal(first.versions.length,1);assert.equal(second.versions.length,2);
assert.equal(resolvePinnedResource([second],pin).value.bodyHeight,9);
assert.deepEqual(first.versions[0].tags,['workshop']);
assert.throws(()=>appendResourceVersion(second,{...input,expectedRevision:1}),/changed/);
assert.throws(()=>appendResourceVersion(first,{...input,expectedRevision:1,value:{...value,bodyDiameter:100}}),/dimension/);
assert.throws(()=>appendResourceVersion(first,{...input,expectedRevision:1,value:{...value,measuredFit:{bodyDiameter:4,printedBoreDiameter:5}}}),/measured fit/);
assert.throws(()=>resolvePinnedResource([],pin),/missing/);
assert.throws(()=>resolvePinnedResource([second],{...pin,version:{...pin.version,name:'different'}}),/differ/);
assert.throws(()=>appendResourceVersion({...first,builtIn:true},{...input,expectedRevision:1}),/built-in/);
const printer={printer:'Ultimaker 2+',curaNozzle:.6,curaMaterial:'PLA',curaQuality:60,curaIntent:'balanced'};
const machine=appendResourceVersion(null,{id:'printer-test',kind:'printer',name:'UM2+',value:printer});
assert.deepEqual(machine.versions[0].value,printer);
assert.throws(()=>appendResourceVersion(null,{id:'bad',kind:'printer',name:'bad',value:{...printer,printer:'Ultimaker 3 Extended'}}),/0.6/);
const project=createProject({id:'project',title:'Test'});project.printer=printer;
addModel(project,createModel({id:'a',name:'a',typeId:'waves'}));
addModel(project,createModel({id:'b',name:'b',typeId:'waves',printerOverrides:{curaNozzle:.8}}));
queueModel(project,'a',{jobId:'ja'});queueModel(project,'b',{jobId:'jb'});
assert.deepEqual(affectedPrintJobs(project,{...printer,curaNozzle:.4}),['ja']);
assert.equal(project.printer.curaNozzle,.6);
const sha='a'.repeat(40),other='b'.repeat(40),at='2026-11-25T12:00:00Z',receipt={sha,at,digest:'digest'};
assert.equal(backupStatus({connected:false,lastUpload:receipt}).kind,'local-only');
assert.equal(backupStatus({connected:true}).kind,'connected');
assert.equal(backupStatus({connected:true,lastCheck:{sha,at}}).kind,'checked');
assert.equal(backupStatus({connected:true,lastUpload:receipt,localDigest:'digest'}).kind,'confirmed-upload');
assert.equal(backupStatus({connected:true,lastUpload:receipt,localDigest:'changed'}).kind,'local-edits');
assert.equal(backupStatus({connected:true,lastUpload:receipt,localDigest:'digest',lastCheck:{sha:other,at}}).kind,'review');
assert.equal(backupStatus({connected:true,lastUpload:{sha:'bad',at,digest:'digest'}}).kind,'connected');
assert.equal(backupStatus({connected:true,operation:'upload'}).kind,'uploading');
assert.equal(backupStatus({connected:true,failed:true}).kind,'failed');
assert(!JSON.stringify(backupStatus({connected:true,lastUpload:receipt,token:'secret'})).includes('secret'));
console.log('Project resource and backup status contracts: pinned measurements, scoped printer defaults, conflict-aware receipts passed.');
