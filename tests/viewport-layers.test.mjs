import assert from 'node:assert/strict';
import {LAYERS_KEY,LAYER_IDS,normalizeLayers,readLayers,writeLayers,layerVisible,setLayerGroup,layerGroupState,layerPreset,visibleForPicking} from '../src/ui/viewport-layers.mjs';
assert.equal(new Set(LAYER_IDS).size,LAYER_IDS.length);
const defaults=normalizeLayers(null);assert(Object.values(defaults).every(Boolean));
const storage=new Map([['unrelated','preserve']]);
const adapter={getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)};
const changed=writeLayers(adapter,{pixelTags:false,wireRoutes:true,invalid:false});
assert.equal(changed.pixelTags,false);assert.equal(changed.pixelReplicas,true);assert(!('invalid' in changed));
assert.deepEqual(readLayers(adapter),changed);assert.equal(storage.get('unrelated'),'preserve');
storage.set(LAYERS_KEY,'broken');assert.deepEqual(readLayers(adapter),defaults);
const blocked={getItem(){throw Error('blocked')},setItem(){throw Error('quota')}};
assert.deepEqual(readLayers(blocked),defaults);assert.equal(writeLayers(blocked,{mountTabs:false}).mountTabs,false);
assert(!layerVisible(defaults,'pixelTags',{baseline:false}));assert(!layerVisible(defaults,'pixelTags',{supported:false}));
assert(!layerVisible(changed,'pixelTags'));assert(layerVisible(changed,'pixelTags',{essential:true}));assert(!layerVisible(changed,'pixelTags',{essential:true,baseline:false}));
assert.throws(()=>layerVisible(defaults,'bad'));
const next=setLayerGroup(defaults,'pixels',false,['pixelTags','pixelReplicas']);
assert.equal(next.socketPreviews,true);assert.deepEqual(layerGroupState(next,'pixels'),{disabled:false,checked:false,indeterminate:true});
assert.deepEqual(layerGroupState(next,'pixels',[]),{disabled:true,checked:false,indeterminate:false});
assert.equal(defaults.pixelTags,true);assert.deepEqual(layerPreset('reset'),defaults);
assert(Object.values(layerPreset('clean')).every(v=>!v));assert(layerPreset('wiring').wireDirections);assert(!layerPreset('wiring').mountTabs);
assert(!visibleForPicking({visible:true,parent:{visible:false}}));assert(visibleForPicking({visible:true,parent:{visible:true}}));
console.log('Viewport layer contracts: storage isolation, stage/capability composition, groups, presets and picking passed.');
