import assert from 'node:assert/strict';
import {createProject,createModel,addModel,closeTab,reorderTabs} from '../studio-documents.js';
import {modelRows,filterRows,reorderOpen,createPreviewQueue,normaliseDrawerZoom} from '../src/ui/model-drawer.mjs';
for(const value of [null,undefined,'',0,6,1.5,'3.5','garbage',' 2 '])assert.equal(normaliseDrawerZoom(value),3);
for(let n=1;n<=5;n++){assert.equal(normaliseDrawerZoom(n),n);assert.equal(normaliseDrawerZoom(String(n)),n);}
const project=createProject({id:'test-drawer',title:'Wonder'});
for(let i=0;i<120;i++)addModel(project,createModel({id:'m'+i,name:i===0?'Red & blue':'Model '+i,typeId:'crystals'}));
const before=JSON.stringify(project),rows=modelRows(project);
assert.equal(rows.length,120);assert.equal(rows[0].label,'Wonder : Red & blue');
assert.equal(filterRows(rows,' RED ').length,1);assert.equal(filterRows(rows,'no match').length,0);
assert.equal(JSON.stringify(project),before,'Projection and filter must not write model data');
const order=reorderOpen(project.tabs,'m0','m2');assert.deepEqual(order.slice(0,3),['m1','m2','m0']);
assert.deepEqual(reorderOpen(project.tabs,'missing','m0'),project.tabs);reorderTabs(project,order);
closeTab(project,'m0');assert.equal(project.models.length,120);assert(!project.tabs.includes('m0'));
let count=0,active=0,maxActive=0;
const queue=createPreviewQueue(async input=>{count++;active++;maxActive=Math.max(maxActive,active);await Promise.resolve();active--;if(input==='bad')return {reason:'Missing saved source'};return {src:'data:image/png;base64,AA=='};},{limit:2,yieldFrame:async()=>{}});
const first=queue.request('a','ok');assert.equal(queue.request('a','ok'),first);await first;
await queue.request('a','ok');assert.equal(count,1);
await Promise.all([queue.request('b','ok'),queue.request('c','ok')]);assert.equal(maxActive,1);
await queue.request('a','ok');assert.equal(count,4,'LRU eviction');
await assert.rejects(queue.request('bad','bad'),/Missing saved source/);
await queue.request('bad','ok');assert.equal(await queue.request('cancel','ok',()=>false),null);
console.log('Model drawer projection, close/reorder, 120 records and preview queue contracts passed');
