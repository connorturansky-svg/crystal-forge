import assert from 'node:assert/strict';
import {calibrationSpec,selectedFitResult,resetFitCalibration,couponLegendCuts} from '../fit-calibration.js';
import {PIXEL_PRESETS,resolvePixelProfile,resolveSocketProfile} from '../pixel-profiles.js';
const s={pixelProfileId:'gumdrop',pixelDiameter:12,pixelFit:.15,pixelProfiles:[],pixelRetentionLip:0};
const spec=calibrationSpec(s,'stepped');
assert.deepEqual(spec.diameters,[11.95,12.05,12.15,12.25,12.35],'5 physical sizes increase left to right in 0.1 mm steps');
assert.deepEqual(spec.captions,['11.95','12.05','12.15','12.25','12.35'],'Exact two-decimal engraving captions');
assert.deepEqual(calibrationSpec(s,'full').diameters,[12,12.15,12.3],'3 body-test diameters');
let changed=selectedFitResult({...s,fitCouponLast:spec},4);
assert.equal(changed.newFit,.35,'Selecting largest test adds 0.2 mm globally');
assert.equal(changed.record.originalFit,.15,'Calibration remembers original');
assert.equal(changed.record.diameter,12.35);
const updated={...s,fitCouponLast:spec,pixelFit:changed.newFit,fitCalibration:changed.record};
assert.equal(resolvePixelProfile(updated).boreDiameter,12.35,'Global pixel uses measured fit');
assert.equal(resolveSocketProfile(updated,{profileId:'seed'}).boreDiameter,5.35,'Other pixel types also inherit global clearance');
const second=selectedFitResult(updated,2);
assert.equal(second.record.originalFit,.15,'Selecting a different sample preserves the original reset baseline');
assert.equal(resetFitCalibration({...updated,fitCalibration:second.record}),.15);
assert.equal(resetFitCalibration(s),null);
assert.throws(()=>selectedFitResult({...s,fitCouponLast:spec},5),/valid printed/);
assert.throws(()=>selectedFitResult({...s,fitCouponLast:spec,pixelProfileId:'seed'},2),/same LED profile/);
assert.equal(PIXEL_PRESETS.length,3);
const strokes=[],fake={Manifold:{cube:size=>({translate:p=>({size,p})})}},hold=x=>{strokes.push(x);return x};
couponLegendCuts(fake,hold,'12.35',20,25,28);
assert(strokes.length>15,'Numeral generator creates actual shallow cut volumes');
assert(strokes.every(x=>x.p[1]<28&&x.p[1]+x.size[1]>28),'Legend engraves the top face');
console.log('PR7 physical coupon calibrated sizes, global fit changes, reset and solid numeric engraving passed');
